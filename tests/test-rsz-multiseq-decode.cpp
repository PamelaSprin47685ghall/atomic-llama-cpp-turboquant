// CPU regression test: batched multi-sequence decode with per-sequence
// histories of different lengths, crossed with the rs_z zero-row moves that
// the recurrent allocator produces.
//
// Proves, on the real tiny MAMBA model and the real llama_decode path:
//   1. each sequence keeps its own history length. Nothing is padded: the
//      batched decode carries exactly one token per sequence, and the lengths
//      differ because the prompts differ and because a sequence leaves and
//      rejoins at position 0;
//   2. after the 3-sequence decode graph is warm, no later decode rebuilds it,
//      for rs_z = 0, 1, 2 and the -1 no-op. graph_builds and patch_binds stay
//      constant, and llama_perf_context reports one graph reuse per decode;
//   3. each sequence's logits in the batched decode are bitwise identical to
//      decoding that sequence alone in its own context;
//   4. the binder context is bitwise identical to the stock context on the
//      same batches, while the stock context DOES rebuild on the same rs_z
//      moves (n_reused == 0). The scenario is therefore real, not a no-op;
//   5. the per-sequence recurrent state rows match the solo decodes.
//
// The test mocks nothing: it reads the live llama_memory_recurrent state, the
// binder counters through llama-nout-state.h, and the graph reuse counter
// through llama_perf_context.
//
// usage: test-rsz-multiseq-decode <tiny-mamba.gguf>
//
// The model is generated by tests/rsz/make_tiny_rsz_mamba.py. The test exits
// 0 only when every check passes and prints a machine-readable final line.

#include "llama.h"

#include "ggml.h"

#include "llama-memory-recurrent.h"
#include "llama-nout-state.h"

#include <algorithm>
#include <cmath>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <vector>

#include <stdlib.h> // setenv/unsetenv

static int g_fail = 0;
static int g_checks_run = 0;

#define CHECK(cond, ...) do { \
    ++g_checks_run; \
    if (!(cond)) { \
        std::fprintf(stderr, "FAIL %s:%d: ", __FILE__, __LINE__); \
        std::fprintf(stderr, __VA_ARGS__); \
        std::fprintf(stderr, "\n"); \
        ++g_fail; \
    } \
} while (0)

// three live sequences: enough for rs_z = 0, 1 and 2 to be distinct rows
static constexpr int N_SEQ = 3;
// physical recurrent-state cells; only N_SEQ are live, so the graph is built
// over a real envelope and every live width is bound in place
static constexpr int N_RS_SLOTS = 8;

struct token_step {
    llama_token  tok;
    llama_pos    pos;
    llama_seq_id seq;
    bool         logits;
};

static llama_context * make_ctx(llama_model * model, bool binder) {
    // the test gates graph reuse and the default binder lane; make
    // both independent of whatever the caller's shell exported
    unsetenv("LLAMA_GRAPH_REUSE_DISABLE");
    if (binder) {
        setenv("GGML_TP5_UNION_BINDER", "1", 1);
    } else {
        unsetenv("GGML_TP5_UNION_BINDER");
    }

    llama_context_params cp = llama_context_default_params();
    cp.n_ctx           = 64;
    cp.n_batch         = 8;
    cp.n_ubatch        = 8;
    cp.n_seq_max       = N_RS_SLOTS;
    cp.n_rs_slots      = N_RS_SLOTS;
    cp.n_rs_seq        = 0;            // no rollback snapshots: replay_len stays 0
    cp.n_outputs_max   = cp.n_seq_max; // contract: n_outputs_max >= n_seq_max
    cp.n_threads       = 1;
    cp.n_threads_batch = 1;
    cp.flash_attn_type = LLAMA_FLASH_ATTN_TYPE_DISABLED;
    cp.offload_kqv     = false;
    cp.no_perf         = true;

    return llama_init_from_model(model, cp);
}

static bool decode_batch(llama_context * ctx, const std::vector<token_step> & ts) {
    llama_batch b = llama_batch_init((int32_t) ts.size(), 0, 1);
    if (!llama_batch_is_complete(&b, (int32_t) ts.size(), false, true)) {
        llama_batch_free(b);
        return false;
    }
    b.n_tokens = (int32_t) ts.size();
    for (size_t i = 0; i < ts.size(); ++i) {
        b.token[i]     = ts[i].tok;
        b.pos[i]       = ts[i].pos;
        b.n_seq_id[i]  = 1;
        b.seq_id[i][0] = ts[i].seq;
        b.logits[i]    = ts[i].logits ? 1 : 0;
    }

    const int rc = llama_decode(ctx, b);
    llama_batch_free(b);
    return rc == 0;
}

// deterministic token ids inside the tiny vocabulary (3 .. 261)
static llama_token tok_at(llama_seq_id seq, llama_pos pos) {
    return (llama_token) (3 + (37 * (int) seq + 11 * (int) pos) % 259);
}

static llama_memory_recurrent * recr(llama_context * ctx) {
    return dynamic_cast<llama_memory_recurrent *>(llama_get_memory(ctx));
}

static int cell_of_seq(const llama_memory_recurrent * mem, llama_seq_id seq) {
    if (mem == nullptr) {
        return -1;
    }
    for (size_t i = 0; i < mem->cells.size(); ++i) {
        if (mem->cells[i].has_seq_id(seq)) {
            return (int) i;
        }
    }
    return -1;
}

// bitwise logits gate. Any difference is a failure: no tolerance, no
// top-k relaxation.
static bool logits_match(llama_context * a, int32_t ia,
                         llama_context * b, int32_t ib,
                         int n_vocab, const char * label, int step, int seq) {
    ++g_checks_run;
    const float * la = llama_get_logits_ith(a, ia);
    const float * lb = llama_get_logits_ith(b, ib);
    if (la == nullptr || lb == nullptr) {
        std::fprintf(stderr, "FAIL step %d seq %d (%s): missing logits (%p, %p)\n",
                     step, seq, label, (const void *) la, (const void *) lb);
        ++g_fail;
        return false;
    }

    if (std::memcmp(la, lb, (size_t) n_vocab * sizeof(float)) == 0) {
        return true;
    }

    int   first   = -1;
    int   max_i   = -1;
    float max_abs = 0.0f;
    for (int i = 0; i < n_vocab; ++i) {
        if (first < 0 && la[i] != lb[i]) {
            first = i;
        }
        const float d = std::fabs(la[i] - lb[i]);
        if (d > max_abs) {
            max_abs = d;
            max_i   = i;
        }
    }
    std::fprintf(stderr,
                 "FAIL step %d seq %d (%s): logits differ (first=%d, max_abs=%g at %d)\n",
                 step, seq, label, first, (double) max_abs, max_i);
    ++g_fail;
    return false;
}

// non-vacuity: two different sequences in the same batched decode must not
// carry identical logits, otherwise the per-sequence equality checks above
// would be comparing one row with itself.
static bool logits_differ(llama_context * a, int32_t ia,
                          llama_context * b, int32_t ib,
                          int n_vocab, const char * label, int step) {
    ++g_checks_run;
    const float * la = llama_get_logits_ith(a, ia);
    const float * lb = llama_get_logits_ith(b, ib);
    if (la == nullptr || lb == nullptr) {
        std::fprintf(stderr, "FAIL step %d (%s): missing logits (%p, %p)\n",
                     step, label, (const void *) la, (const void *) lb);
        ++g_fail;
        return false;
    }
    if (std::memcmp(la, lb, (size_t) n_vocab * sizeof(float)) != 0) {
        return true;
    }
    std::fprintf(stderr, "FAIL step %d (%s): rows %d and %d are identical\n",
                 step, label, ia, ib);
    ++g_fail;
    return false;
}

// the whole recurrent state must match the stock context cell for cell
static bool compare_all_states(llama_context * a, llama_context * b, int step) {
    auto * ma = recr(a);
    ++g_checks_run;
    auto * mb = recr(b);
    if (ma == nullptr || mb == nullptr) {
        std::fprintf(stderr, "FAIL step %d: missing recurrent memory\n", step);
        ++g_fail;
        return false;
    }
    if (ma->r_l.size() != mb->r_l.size() || ma->s_l.size() != mb->s_l.size()) {
        std::fprintf(stderr, "FAIL step %d: layer count differs\n", step);
        ++g_fail;
        return false;
    }
    for (size_t il = 0; il < ma->r_l.size(); ++il) {
        for (int which = 0; which < 2; ++which) {
            const ggml_tensor * ta = which == 0 ? ma->r_l[il] : ma->s_l[il];
            const ggml_tensor * tb = which == 0 ? mb->r_l[il] : mb->s_l[il];
            if (ta == nullptr || tb == nullptr) {
                std::fprintf(stderr, "FAIL step %d: layer %zu %s tensor is null\n",
                             step, il, which == 0 ? "r_l" : "s_l");
                ++g_fail;
                return false;
            }
            const size_t na = ggml_nbytes(ta);
            const size_t nb = ggml_nbytes(tb);
            if (na != nb || std::memcmp(ta->data, tb->data, na) != 0) {
                std::fprintf(stderr,
                             "FAIL step %d: layer %zu %s state differs (%zu vs %zu bytes)\n",
                             step, il, which == 0 ? "r_l" : "s_l", na, nb);
                ++g_fail;
                return false;
            }
        }
    }
    return true;
}

// one sequence's state row must match the row of its solo decode. The cell
// index is looked up from the live memory, never assumed.
static bool compare_seq_state(llama_context * a, llama_seq_id sa,
                              llama_context * b, llama_seq_id sb,
                              int step, int seq) {
    ++g_checks_run;
    auto * ma = recr(a);
    auto * mb = recr(b);
    if (ma == nullptr || mb == nullptr) {
        std::fprintf(stderr, "FAIL step %d seq %d: missing recurrent memory\n", step, seq);
        ++g_fail;
        return false;
    }
    const int ca = cell_of_seq(ma, sa);
    const int cb = cell_of_seq(mb, sb);
    if (ca < 0 || cb < 0) {
        std::fprintf(stderr, "FAIL step %d seq %d: no live cell (batched %d, solo %d)\n",
                     step, seq, ca, cb);
        ++g_fail;
        return false;
    }
    if (ma->r_l.size() != mb->r_l.size() || ma->s_l.size() != mb->s_l.size()) {
        std::fprintf(stderr, "FAIL step %d seq %d: layer count differs\n", step, seq);
        ++g_fail;
        return false;
    }
    for (size_t il = 0; il < ma->r_l.size(); ++il) {
        for (int which = 0; which < 2; ++which) {
            const ggml_tensor * ta = which == 0 ? ma->r_l[il] : ma->s_l[il];
            const ggml_tensor * tb = which == 0 ? mb->r_l[il] : mb->s_l[il];
            if (ta == nullptr || tb == nullptr) {
                std::fprintf(stderr, "FAIL step %d seq %d: layer %zu %s tensor is null\n",
                             step, seq, il, which == 0 ? "r_l" : "s_l");
                ++g_fail;
                return false;
            }
            const size_t rowa = ggml_row_size(ta->type, ta->ne[0]);
            const size_t rowb = ggml_row_size(tb->type, tb->ne[0]);
            if (rowa != rowb) {
                std::fprintf(stderr, "FAIL step %d seq %d: layer %zu %s row size %zu != %zu\n",
                             step, seq, il, which == 0 ? "r_l" : "s_l", rowa, rowb);
                ++g_fail;
                return false;
            }
            const char * pa = (const char *) ta->data + (size_t) ca * ta->nb[1];
            const char * pb = (const char *) tb->data + (size_t) cb * tb->nb[1];
            if (std::memcmp(pa, pb, rowa) != 0) {
                size_t first_byte = 0;
                while (first_byte < rowa && pa[first_byte] == pb[first_byte]) {
                    ++first_byte;
                }
                std::fprintf(stderr,
                             "FAIL step %d seq %d: layer %zu %s state row differs "
                             "(cell %d vs %d, first byte %zu of %zu)\n",
                             step, seq, il, which == 0 ? "r_l" : "s_l", ca, cb, first_byte, rowa);
                ++g_fail;
                return false;
            }
        }
    }
    return true;
}

static void check_counters(const llama_nkv_ctx_state & st, int step,
                           size_t expect_builds, size_t expect_binds) {
    CHECK(st.nkv_enabled, "step %d: binder not enabled", step);
    CHECK(st.record_valid, "step %d: no valid graph record", step);
    CHECK(!st.env_disabled, "step %d: envelope disabled", step);
    CHECK(st.c_shape_fail == 0, "step %d: shape analysis failed (%zu)", step, st.c_shape_fail);
    CHECK(st.c_graph_builds == expect_builds,
          "step %d: graph_builds %zu != expected %zu", step, st.c_graph_builds, expect_builds);
    // every rebuild on this supported path is an envelope build + analysis;
    // a stock fallback would make these diverge from graph_builds.
    CHECK(st.c_env_builds == expect_builds,
          "step %d: env_builds %zu != graph_builds %zu", step, st.c_env_builds, expect_builds);
    CHECK(st.c_shape_analyses == expect_builds,
          "step %d: shape_analyses %zu != graph_builds %zu", step, st.c_shape_analyses, expect_builds);
    CHECK(st.c_refused_rs_z == 0, "step %d: refused_rs_z %zu != 0", step, st.c_refused_rs_z);
    CHECK(st.c_refused_nrs == 0, "step %d: refused_nrs %zu != 0", step, st.c_refused_nrs);
    CHECK(st.c_patch_binds == expect_binds,
          "step %d: patch_binds %zu != expected %zu", step, st.c_patch_binds, expect_binds);
    CHECK(st.c_applied == st.c_patch_binds,
          "step %d: applied %zu != patch_binds %zu", step, st.c_applied, st.c_patch_binds);
    CHECK(st.shape_map.rs_head_valid, "step %d: rs_head map invalid", step);
    CHECK(st.shape_map.nrs_valid, "step %d: n_rs map invalid", step);
}

int main(int argc, char ** argv) {
    if (argc != 2) {
        std::fprintf(stderr, "usage: %s <tiny-mamba.gguf>\n", argv[0]);
        return 2;
    }

    llama_backend_init();

    llama_model_params mp = llama_model_default_params();
    mp.n_gpu_layers = 0;

    llama_model * model = llama_model_load_from_file(argv[1], mp);
    if (model == nullptr) {
        std::fprintf(stderr, "FAIL: cannot load model %s\n", argv[1]);
        llama_backend_free();
        return 1;
    }

    const llama_vocab * vocab = llama_model_get_vocab(model);
    const int n_vocab = (int) llama_vocab_n_tokens(vocab);
    if (n_vocab < 262) {
        std::fprintf(stderr, "FAIL: tiny model has %d tokens, expected >= 262\n", n_vocab);
        llama_model_free(model);
        llama_backend_free();
        return 1;
    }

    llama_context * ctx_on  = make_ctx(model, true);
    llama_context * ctx_off = make_ctx(model, false);
    llama_context * ctx_solo[N_SEQ];
    for (int s = 0; s < N_SEQ; ++s) {
        ctx_solo[s] = make_ctx(model, false);
    }

    bool ctx_ok = ctx_on != nullptr && ctx_off != nullptr;
    for (int s = 0; s < N_SEQ; ++s) {
        ctx_ok = ctx_ok && ctx_solo[s] != nullptr;
    }
    if (!ctx_ok) {
        std::fprintf(stderr, "FAIL: context creation failed\n");
        if (ctx_on)  llama_free(ctx_on);
        if (ctx_off) llama_free(ctx_off);
        for (int s = 0; s < N_SEQ; ++s) {
            if (ctx_solo[s]) llama_free(ctx_solo[s]);
        }
        llama_model_free(model);
        llama_backend_free();
        return 1;
    }

    auto & st = llama_nkv_ctx_state_get(ctx_on);
    CHECK(st.nkv_enabled, "binder context did not enable the union binder");
    CHECK(st.union_binder.has(llama_union_param_kind::rs_z), "rs_z binding is not registered");

    auto * mem_on  = recr(ctx_on);
    auto * mem_off = recr(ctx_off);
    CHECK(mem_on  != nullptr, "binder context memory is not recurrent");
    CHECK(mem_off != nullptr, "stock context memory is not recurrent");
    if (mem_on == nullptr || mem_off == nullptr) {
        llama_free(ctx_on);
        llama_free(ctx_off);
        for (int s = 0; s < N_SEQ; ++s) {
            llama_free(ctx_solo[s]);
        }
        llama_model_free(model);
        llama_backend_free();
        return 1;
    }
    CHECK(mem_on->size == (uint32_t) N_RS_SLOTS, "state capacity %u != %d", mem_on->size, N_RS_SLOTS);

    // ---- prefill: one prompt per sequence, distinct lengths, no padding ----
    const int prefill_len[N_SEQ] = { 5, 2, 7 };
    CHECK(prefill_len[0] != prefill_len[1] && prefill_len[1] != prefill_len[2] &&
          prefill_len[0] != prefill_len[2],
          "prefill lengths must differ (no padding): %d %d %d",
          prefill_len[0], prefill_len[1], prefill_len[2]);

    llama_pos next_pos[N_SEQ] = { 0, 0, 0 };

    for (int s = 0; s < N_SEQ; ++s) {
        std::vector<token_step> ts;
        for (int i = 0; i < prefill_len[s]; ++i) {
            ts.push_back({ tok_at(s, i), (llama_pos) i, (llama_seq_id) s, i + 1 == prefill_len[s] });
        }

        CHECK(decode_batch(ctx_on, ts),        "prefill seq %d: ON decode failed", s);
        CHECK(decode_batch(ctx_off, ts),       "prefill seq %d: OFF decode failed", s);
        CHECK(decode_batch(ctx_solo[s], ts),   "prefill seq %d: solo decode failed", s);

        const int last = prefill_len[s] - 1;
        logits_match(ctx_on,  last, ctx_off,       last, n_vocab, "prefill on/off",  -1, s);
        logits_match(ctx_on,  last, ctx_solo[s],   last, n_vocab, "prefill on/solo", -1, s);
        logits_match(ctx_off, last, ctx_solo[s],   last, n_vocab, "prefill off/solo", -1, s);

        // the prefill itself already moves rs_z: each new sequence takes the
        // next free cell and that cell is the zero row
        CHECK(mem_on->rs_z  == s, "prefill seq %d: ON rs_z %d != %d", s, mem_on->rs_z, s);
        CHECK(mem_off->rs_z == s, "prefill seq %d: OFF rs_z %d != %d", s, mem_off->rs_z, s);
        CHECK(mem_on->head  == (uint32_t) s,
              "prefill seq %d: ON head %u != %d", s, mem_on->head, s);
        CHECK(mem_on->n     == (uint32_t) 1,
              "prefill seq %d: ON n_rs %u != 1", s, mem_on->n);
        compare_seq_state(ctx_on, s, ctx_solo[s], s, -1, s);
        next_pos[s] = prefill_len[s];
    }

    CHECK(st.c_graph_builds == (size_t) N_SEQ,
          "prefill: graph_builds %zu != %d (one build per distinct prompt shape)",
          st.c_graph_builds, N_SEQ);

    // ---- steady-state decode: one token per sequence, rs_z moves ----
    //
    // Every step carries the same ubatch skeleton (3 tokens, 3 sequences, one
    // token each), so only the recurrent runtime parameters move. A sequence
    // that is released and rejoined becomes the zero row: with the other two
    // cells occupied, its cell index is exactly the rs_z value.
    struct step {
        const char * name;
        int          rm_seq;      // -1: every sequence continues
        int32_t      expect_rs_z;
    };

    const step steps[] = {
        { "S0 all continue",       -1, -1 },
        { "S1 all continue",       -1, -1 },
        { "S2 seq0 rejoins",        0,  0 },
        { "S3 all continue",       -1, -1 },
        { "S4 seq1 rejoins",        1,  1 },
        { "S5 all continue",       -1, -1 },
        { "S6 seq2 rejoins",        2,  2 },
        { "S7 all continue",       -1, -1 },
        { "S8 seq0 rejoins again",  0,  0 },
        { "S9 all continue",       -1, -1 },
    };
    const size_t n_steps = sizeof(steps) / sizeof(steps[0]);

    size_t warm_builds = 0;
    size_t warm_binds  = 0;
    int32_t prev_rs_z  = -2;
    int n_reuse_on     = 0;
    std::vector<int32_t> rs_z_seen;

    for (size_t i = 0; i < n_steps; ++i) {
        const step & s = steps[i];
        const int step_i = (int) i;

        if (s.rm_seq >= 0) {
            const llama_seq_id q = (llama_seq_id) s.rm_seq;
            CHECK(llama_memory_seq_rm(llama_get_memory(ctx_on),     q, -1, -1),
                  "step %d (%s): ON seq_rm failed", step_i, s.name);
            CHECK(llama_memory_seq_rm(llama_get_memory(ctx_off),    q, -1, -1),
                  "step %d (%s): OFF seq_rm failed", step_i, s.name);
            CHECK(llama_memory_seq_rm(llama_get_memory(ctx_solo[q]), q, -1, -1),
                  "step %d (%s): solo seq_rm failed", step_i, s.name);
            next_pos[q] = 0;
        }

        std::vector<token_step> ts;
        for (int q = 0; q < N_SEQ; ++q) {
            ts.push_back({ tok_at(q, next_pos[q]), next_pos[q], (llama_seq_id) q, true });
        }
        CHECK(ts[0].pos != ts[1].pos && ts[1].pos != ts[2].pos && ts[0].pos != ts[2].pos,
              "step %d (%s): positions %d %d %d are not distinct (lengths must differ)",
              step_i, s.name, (int) ts[0].pos, (int) ts[1].pos, (int) ts[2].pos);

        llama_perf_context_reset(ctx_on);
        llama_perf_context_reset(ctx_off);

        CHECK(decode_batch(ctx_on, ts), "step %d (%s): ON decode failed", step_i, s.name);
        const llama_perf_context_data pon = llama_perf_context(ctx_on);

        CHECK(decode_batch(ctx_off, ts), "step %d (%s): OFF decode failed", step_i, s.name);
        const llama_perf_context_data poff = llama_perf_context(ctx_off);

        for (int q = 0; q < N_SEQ; ++q) {
            const token_step one = { ts[q].tok, ts[q].pos, ts[q].seq, true };
            CHECK(decode_batch(ctx_solo[q], { one }),
                  "step %d (%s): solo seq %d decode failed", step_i, s.name, q);
        }

        // live recurrent state: the same row selection in both contexts
        CHECK(mem_on->rs_z  == s.expect_rs_z,
              "step %d (%s): ON rs_z %d != expected %d",
              step_i, s.name, mem_on->rs_z, s.expect_rs_z);
        CHECK(mem_off->rs_z == s.expect_rs_z,
              "step %d (%s): OFF rs_z %d != expected %d",
              step_i, s.name, mem_off->rs_z, s.expect_rs_z);
        CHECK(mem_on->head  == 0, "step %d (%s): ON head %u != 0", step_i, s.name, mem_on->head);
        CHECK(mem_off->head == 0, "step %d (%s): OFF head %u != 0", step_i, s.name, mem_off->head);
        CHECK(mem_on->n  == (uint32_t) N_SEQ, "step %d (%s): ON n_rs %u != %d", step_i, s.name, mem_on->n, N_SEQ);
        CHECK(mem_off->n == (uint32_t) N_SEQ, "step %d (%s): OFF n_rs %u != %d", step_i, s.name, mem_off->n, N_SEQ);
        rs_z_seen.push_back(mem_on->rs_z);

        // per-sequence logits: batched binder vs batched stock vs solo decode
        for (int q = 0; q < N_SEQ; ++q) {
            logits_match(ctx_on,  q, ctx_off,     q, n_vocab, "batched on/off",   step_i, q);
            logits_match(ctx_on,  q, ctx_solo[q], 0, n_vocab, "batched on/solo",  step_i, q);
            logits_match(ctx_off, q, ctx_solo[q], 0, n_vocab, "batched off/solo", step_i, q);
            compare_seq_state(ctx_on, q, ctx_solo[q], q, step_i, q);
        }
        // the three rows must be distinct: a gather that returned one row for
        // every sequence would make the equality checks above vacuous
        logits_differ(ctx_on, 0, ctx_on, 1, n_vocab, "batched rows 0/1", step_i);
        logits_differ(ctx_on, 0, ctx_on, 2, n_vocab, "batched rows 0/2", step_i);
        logits_differ(ctx_on, 1, ctx_on, 2, n_vocab, "batched rows 1/2", step_i);
        compare_all_states(ctx_on, ctx_off, step_i);

        // warm-graph gate: the first 3-sequence decode builds, nothing after
        // it may rebuild or call the binder
        if (i == 0) {
            warm_builds = st.c_graph_builds;
            warm_binds  = st.c_patch_binds;
            CHECK(warm_builds == (size_t) N_SEQ + 1,
                  "step 0 (%s): warm graph_builds %zu != %d (3 prefills + 1 decode)",
                  s.name, warm_builds, N_SEQ + 1);
            CHECK(warm_binds == (size_t) N_SEQ + 1,
                  "step 0 (%s): warm patch_binds %zu != %d",
                  s.name, warm_binds, N_SEQ + 1);
        }
        CHECK(st.c_graph_builds == warm_builds,
              "step %d (%s): graph_builds %zu != warm %zu (rebuild after warm)",
              step_i, s.name, st.c_graph_builds, warm_builds);
        CHECK(st.c_patch_binds == warm_binds,
              "step %d (%s): patch_binds %zu != warm %zu (an rs_z-only move called the binder)",
              step_i, s.name, st.c_patch_binds, warm_binds);
        check_counters(st, step_i, warm_builds, warm_binds);

        CHECK(st.record_bound_n_rs == mem_on->n,
              "step %d (%s): record_bound_n_rs %u != live n_rs %u",
              step_i, s.name, st.record_bound_n_rs, mem_on->n);
        CHECK(st.record_bound_rs_head == mem_on->head,
              "step %d (%s): record_bound_rs_head %u != live head %u",
              step_i, s.name, st.record_bound_rs_head, mem_on->head);
        CHECK(st.record_cap_nrs == mem_on->size,
              "step %d (%s): record_cap_nrs %u != capacity %u",
              step_i, s.name, st.record_cap_nrs, mem_on->size);
        CHECK(st.record_cap_nout == (uint32_t) N_RS_SLOTS,
              "step %d (%s): record_cap_nout %u != n_outputs_max %d",
              step_i, s.name, st.record_cap_nout, N_RS_SLOTS);

        // graph reuse: the binder reuses every decode after the warm build;
        // the stock context rebuilds whenever rs_z moves
        if (i == 0) {
            CHECK(pon.n_reused == 0,
                  "step 0 (%s): ON reused %d != 0 (expected the warm build)",
                  s.name, pon.n_reused);
        } else {
            CHECK(pon.n_reused == 1,
                  "step %d (%s): ON reused %d != 1 (graph not reused)",
                  step_i, s.name, pon.n_reused);
            ++n_reuse_on;
        }
        const int expect_off_reuse = prev_rs_z == s.expect_rs_z ? 1 : 0;
        CHECK(poff.n_reused == expect_off_reuse,
              "step %d (%s): OFF reused %d != %d (stock must rebuild on an rs_z move)",
              step_i, s.name, poff.n_reused, expect_off_reuse);
        prev_rs_z = s.expect_rs_z;

        for (int q = 0; q < N_SEQ; ++q) {
            next_pos[q] += 1;
        }
    }

    // coverage: the run must have produced every rs_z kind
    CHECK(std::find(rs_z_seen.begin(), rs_z_seen.end(), -1) != rs_z_seen.end(),
          "rs_z never took the -1 no-op value");
    CHECK(std::find(rs_z_seen.begin(), rs_z_seen.end(), 0) != rs_z_seen.end(),
          "rs_z never took row 0");
    CHECK(std::find(rs_z_seen.begin(), rs_z_seen.end(), 1) != rs_z_seen.end(),
          "rs_z never took row 1");
    CHECK(std::find(rs_z_seen.begin(), rs_z_seen.end(), 2) != rs_z_seen.end(),
          "rs_z never took row 2");
    CHECK(n_reuse_on == (int) n_steps - 1,
          "ON reused %d times, expected %zu", n_reuse_on, n_steps - 1);
    CHECK(st.c_graph_builds == (size_t) N_SEQ + 1,
          "final graph_builds %zu != %d", st.c_graph_builds, N_SEQ + 1);

    std::printf("RSZ_MULTISEQ_STATS graph_builds=%zu env_builds=%zu patch_binds=%zu "
                "refused_rs_z=%zu refused_nrs=%zu shape_fail=%zu env_disabled=%d "
                "cap_nrs=%u warm_builds=%zu on_reuses=%d rs_z_seen=",
                st.c_graph_builds, st.c_env_builds, st.c_patch_binds,
                st.c_refused_rs_z, st.c_refused_nrs, st.c_shape_fail, st.env_disabled ? 1 : 0,
                st.record_cap_nrs, warm_builds, n_reuse_on);
    for (size_t i = 0; i < rs_z_seen.size(); ++i) {
        std::printf("%s%d", i == 0 ? "" : ",", rs_z_seen[i]);
    }
    std::printf("\n");

    llama_free(ctx_on);
    llama_free(ctx_off);
    for (int s = 0; s < N_SEQ; ++s) {
        llama_free(ctx_solo[s]);
    }
    llama_model_free(model);
    llama_backend_free();

    if (g_checks_run == 0) {
        std::fprintf(stderr, "RSZ_MULTISEQ_TEST UNPROVEN reason=no_check_ran checks=0\n");
        return 2;
    }
    if (g_fail != 0) {
        std::printf("RSZ_MULTISEQ_TEST FAIL %d check(s)\n", g_fail);
        return 1;
    }
    std::printf("RSZ_MULTISEQ_TEST PASS\n");
    return 0;
}
