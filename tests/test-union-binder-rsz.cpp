// CPU unit test: rs_z / recurrent-state union binder.
//
// Proves, on a real tiny MAMBA model and the real llama_decode path:
//   1. the union graph is built at the full recurrent-state envelope and
//      reused across rs_z moves (no rebuild);
//   2. n_rs / head moves are bound in place and rs_z moves update the
//      runtime index input, not the graph topology;
//   3. the bound view offsets and sizes match the live memory state;
//   4. zero-before-gather is an explicit graph dependency (the gathers
//      consume the zero-row op output);
//   5. three legs -- binder ON (GGML_TP5_UNION_BINDER=1), explicit OFF
//      (=0) and stock (unset) -- produce bitwise-identical logits and
//      recurrent-state buffers after every decode;
//   6. the logits are non-vacuous: finite, variance > 0 and at least two
//      distinct values at every step. The previous tiny GGUF read its
//      leading tensors as zeros, so every logit was 0 and leg equality held
//      for the wrong reason.
//
// The test never mocks the binder, the memory or the counters: it reads the
// per-context state through llama-nout-state.h and the live graph tensors
// through the recorded tensor list.
//
// usage: test-union-binder-rsz <tiny-mamba.gguf>
// env:   RSZ_LOGITS_DIR=<dir> writes logits-{on,off,stock}.bin (raw float32,
//        one requested output row per step, in step order) so an external
//        sha256sum can tabulate the legs.
//
// The model is generated by tests/rsz/make_tiny_rsz_mamba.py. The test exits
// 0 only when every check passes and prints a machine-readable final line.

#include "llama.h"

#include "ggml.h"

#include "llama-memory-recurrent.h"
#include "llama-nout-state.h"

#include <algorithm>
#include <cmath>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

#include <stdlib.h> // setenv/unsetenv

static int g_fail = 0;
static int g_checks_run = 0;

#define CHECK(cond, ...) do { \
    ++g_checks_run; \
    if (!(cond)) { \
        std::fprintf(stderr, "FAIL %s:%d: ", __FILE__, __LINE__); \
        std::fprintf(stderr, __VA_ARGS__); \
        std::fprintf(stderr, "\n"); \
        ++g_fail; \
    } \
} while (0)

static llama_context * make_ctx(llama_model * model, const char * binder_env) {
    // binder_env == nullptr leaves the gate unset (stock); "1" enables the
    // binder; "0" is the explicit-off leg. The gate is read once, in the
    // llama_context constructor, and the binder state slot is per context, so
    // the three settings can coexist in one process.
    if (binder_env != nullptr) {
        setenv("GGML_TP5_UNION_BINDER", binder_env, 1);
    } else {
        unsetenv("GGML_TP5_UNION_BINDER");
    }

    llama_context_params cp = llama_context_default_params();
    cp.n_ctx           = 32;
    cp.n_batch         = 8;
    cp.n_ubatch        = 8;
    cp.n_seq_max       = 8;
    cp.n_rs_slots      = 8;   // eight recurrent state cells; phase B uses fillers
    cp.n_rs_seq        = 0;   // no rollback snapshots: replay_len stays 0
    cp.n_outputs_max   = cp.n_seq_max; // contract: n_outputs_max >= n_seq_max
    cp.n_threads       = 1;
    cp.n_threads_batch = 1;
    cp.flash_attn_type = LLAMA_FLASH_ATTN_TYPE_DISABLED;
    cp.offload_kqv     = false;
    cp.no_perf         = true;

    return llama_init_from_model(model, cp);
}

// decode_one requests exactly one logits row (token 0); every trace in this
// test keeps that single-row shape, so llama_get_logits_ith(ctx, 0) is the
// complete output. A trace that requests more rows would need
// compare_logits()/dump_step() to loop over them.
static bool decode_one(llama_context * ctx, llama_token tok, llama_pos pos, llama_seq_id seq) {
    llama_batch b = llama_batch_init(1, 0, 1);
    if (!llama_batch_is_complete(&b, 1, false, true)) {
        llama_batch_free(b);
        return false;
    }
    b.n_tokens    = 1;
    b.token[0]    = tok;
    b.pos[0]      = pos;
    b.n_seq_id[0] = 1;
    b.seq_id[0][0] = seq;
    b.logits[0]   = 1;

    const int rc = llama_decode(ctx, b);
    llama_batch_free(b);
    return rc == 0;
}

static llama_memory_recurrent * recr(llama_context * ctx) {
    return dynamic_cast<llama_memory_recurrent *>(llama_get_memory(ctx));
}


static size_t find_tensor_index(const llama_nkv_ctx_state & st, const char * name) {
    for (size_t k = 0; k < st.record_t.size(); ++k) {
        if (st.record_t[k] != nullptr && std::strcmp(st.record_t[k]->name, name) == 0) {
            return k;
        }
    }
    return SIZE_MAX;
}
static const ggml_tensor * find_tensor(const llama_nkv_ctx_state & st, const char * name) {
    const size_t k = find_tensor_index(st, name);
    return k == SIZE_MAX ? nullptr : st.record_t[k];
}

// live tensor metadata must agree with the memory state the binder claims to
// have bound. This is the direct "binding is real" check: the offsets are
// recomputed from the live memory, not from the binder's own bookkeeping.
static void check_live_tensors(llama_context * ctx, const llama_nkv_ctx_state & st, int step, int n_seqs) {
    auto * mem = recr(ctx);
    CHECK(mem != nullptr, "step %d: memory is not llama_memory_recurrent", step);
    if (mem == nullptr) {
        return;
    }

    int n_copy_dst  = 0;
    int n_head_view = 0;

    for (size_t k = 0; k < st.record_t.size(); ++k) {
        ggml_tensor * t = st.record_t[k];
        if (t == nullptr) {
            continue;
        }

        if (std::strcmp(t->name, "union_rs_copy_dst") == 0) {
            ++n_copy_dst;
            CHECK(t->view_src != nullptr, "step %d: copy_dst %zu has no view_src", step, k);
            if (t->view_src == nullptr) {
                continue;
            }
            const int64_t row = (int64_t) t->view_src->nb[1];
            CHECK(t->ne[1] == (int64_t) mem->n - n_seqs,
                  "step %d: copy_dst %zu rows %lld != n_rs %u - n_seqs %d",
                  step, k, (long long) t->ne[1], mem->n, n_seqs);
            CHECK((int64_t) t->view_offs == (int64_t) (mem->head + n_seqs) * row,
                  "step %d: copy_dst %zu offset %lld != (head %u + n_seqs %d) * row %lld",
                  step, k, (long long) t->view_offs, mem->head, n_seqs, (long long) row);
            const char * expect_data = t->view_src->data != nullptr
                ? (const char *) t->view_src->data + t->view_offs
                : nullptr;
            CHECK(t->data == expect_data,
                  "step %d: copy_dst %zu data %p != view_src->data + offs %p",
                  step, k, (void *) t->data, (void *) expect_data);
        } else if (std::strcmp(t->name, "union_rs_head_view") == 0) {
            ++n_head_view;
            CHECK(t->view_src != nullptr, "step %d: head_view %zu has no view_src", step, k);
            if (t->view_src == nullptr) {
                continue;
            }
            const int64_t row = (int64_t) t->view_src->nb[1];
            CHECK((int64_t) t->view_offs == (int64_t) mem->head * row,
                  "step %d: head_view %zu offset %lld != head %u * row %lld",
                  step, k, (long long) t->view_offs, mem->head, (long long) row);
            const char * expect_data = t->view_src->data != nullptr
                ? (const char *) t->view_src->data + t->view_offs
                : nullptr;
            CHECK(t->data == expect_data,
                  "step %d: head_view %zu data %p != view_src->data + offs %p",
                  step, k, (void *) t->data, (void *) expect_data);
        }
    }

    CHECK(n_copy_dst  > 0, "step %d: no union_rs_copy_dst tensor recorded", step);
    CHECK(n_head_view > 0, "step %d: no union_rs_head_view tensor recorded", step);

    // union_rs_copy is the input tensor whose width is the live n_rs. The
    // build envelope sized it at the full state capacity, so a live n_rs
    // below the capacity is safe; the binder must still narrow the live
    // tensor and keep the recorded byte envelope at capacity (OOB backstop).
    const size_t scopy_idx = find_tensor_index(st, "union_rs_copy");
    CHECK(scopy_idx != SIZE_MAX, "step %d: union_rs_copy is not recorded", step);
    if (scopy_idx != SIZE_MAX) {
        const ggml_tensor * scopy = st.record_t[scopy_idx];
        CHECK(scopy->ne[0] == (int64_t) mem->n,
              "step %d: copy width %lld != live n_rs %u",
              step, (long long) scopy->ne[0], mem->n);
        CHECK(st.record_bytes[scopy_idx] >= (size_t) mem->size * sizeof(int32_t),
              "step %d: copy byte envelope %zu < capacity %u * 4",
              step, st.record_bytes[scopy_idx], mem->size);
    }

    // The split views must follow the same live length: main is n_seqs wide,
    // extra is n_rs - n_seqs wide. A stale extra width would gather rows past
    // the live state and copy them into the cache.
    const ggml_tensor * smain = find_tensor(st, "union_rs_copy_main");
    CHECK(smain != nullptr, "step %d: union_rs_copy_main is not recorded", step);
    if (smain != nullptr) {
        CHECK(smain->ne[0] == n_seqs,
              "step %d: copy_main width %lld != n_seqs %d",
              step, (long long) smain->ne[0], n_seqs);
    }
    const ggml_tensor * sextra = find_tensor(st, "union_rs_copy_extra");
    CHECK(sextra != nullptr, "step %d: union_rs_copy_extra is not recorded", step);
    if (sextra != nullptr) {
        CHECK(sextra->ne[0] == (int64_t) mem->n - n_seqs,
              "step %d: copy_extra width %lld != n_rs %u - n_seqs %d",
              step, (long long) sextra->ne[0], mem->n, n_seqs);
    }
}

// The binder path replaces the stock zero-row view/scale with an explicit
// dependency: an I32 index input selects the row and a MAP_CUSTOM2 op zeroes
// it in place; both state gathers consume that op's output. This is the
// zero-before-gather order as a graph edge, not a build-order convention.
static void check_zero_row(llama_context * ctx, const llama_nkv_ctx_state & st, int step) {
    auto * mem = recr(ctx);
    CHECK(mem != nullptr, "step %d: memory is not recurrent", step);
    if (mem == nullptr) {
        return;
    }

    const ggml_tensor * zidx = find_tensor(st, "union_rs_zero_index");
    CHECK(zidx != nullptr, "step %d: union_rs_zero_index is not recorded", step);
    if (zidx != nullptr) {
        CHECK(zidx->type == GGML_TYPE_I32 && zidx->ne[0] == 1,
              "step %d: zero index is not I32[1]", step);
        CHECK(zidx->data != nullptr, "step %d: zero index has no host data", step);
        // The bound row is not readable here: ggml-alloc recycles an input's
        // storage once its last consumer has been allocated, and the zero-row
        // op is that consumer (a later node in the same graph reuses the
        // slot). The runtime row selection is proven behaviorally instead:
        // the zero-row op consumes this tensor (checked below), and
        // compare_states() requires the recurrent state to match the stock
        // context bitwise -- stock zeroes exactly mem->rs_z, so a stale or
        // build-time row would change the state.
        //
        // The ROW VALUE itself -- rs_idx[seq]*mem_size + rs_z, i.e. the row
        // the gathers read rather than the cell index -- has no model-free
        // home here: it needs a hand-driven rs_idx and a host-readable index
        // tensor, which this test cannot build through llama_decode. It is
        // pinned by tests/test-rs-ring-relay.cpp arms R1 and SWEEP (and by
        // test-rsz-selection-write arm (iv)), which drive rs_idx through the
        // public memory API and read the row back from the index tensor.
    }

    const ggml_tensor * zrow = find_tensor(st, "union_rs_zero_row");
    CHECK(zrow != nullptr, "step %d: union_rs_zero_row is not recorded", step);
    if (zrow == nullptr) {
        return;
    }
    CHECK(zrow->op == GGML_OP_MAP_CUSTOM2,
          "step %d: zero row op is %d, not MAP_CUSTOM2", step, (int) zrow->op);
    CHECK(zrow->view_src != nullptr, "step %d: zero row has no view_src", step);
    CHECK(zrow->src[0] == zrow->view_src,
          "step %d: zero row is not an in-place view of its state source", step);
    CHECK(zrow->src[1] == zidx,
          "step %d: zero row does not consume the runtime index", step);
    if (zrow->view_src != nullptr) {
        CHECK(zrow->data == zrow->view_src->data,
              "step %d: zero row data %p != state data %p",
              step, (void *) zrow->data, (void *) zrow->view_src->data);
    }

    // explicit zero-before-gather: at least one gather/scan consumes the
    // zero-row output. The conv path uses GET_ROWS; the ssm path reshapes the
    // same output and feeds it to SSM_SCAN.
    int consumers = 0;
    for (const ggml_tensor * t : st.record_t) {
        if (t == nullptr) {
            continue;
        }
        if ((t->op == GGML_OP_GET_ROWS || t->op == GGML_OP_RESHAPE ||
             t->op == GGML_OP_SSM_SCAN) && t->src[0] == zrow) {
            ++consumers;
        }
    }
    CHECK(consumers > 0, "step %d: no gather/scan consumes union_rs_zero_row", step);
}

static void check_counters(const llama_nkv_ctx_state & st, int step, size_t expect_builds) {
    CHECK(st.nkv_enabled, "step %d: binder not enabled", step);
    CHECK(st.record_valid, "step %d: no valid graph record", step);
    CHECK(!st.env_disabled, "step %d: envelope disabled", step);
    CHECK(st.c_shape_fail == 0, "step %d: shape analysis failed (%zu)", step, st.c_shape_fail);
    CHECK(st.c_graph_builds == expect_builds,
          "step %d: graph_builds %zu != expected %zu", step, st.c_graph_builds, expect_builds);
    // every rebuild on this supported path is an envelope build + analysis;
    // a stock fallback would make these diverge from graph_builds.
    CHECK(st.c_env_builds == expect_builds,
          "step %d: env_builds %zu != graph_builds %zu", step, st.c_env_builds, expect_builds);
    CHECK(st.c_shape_analyses == expect_builds,
          "step %d: shape_analyses %zu != graph_builds %zu", step, st.c_shape_analyses, expect_builds);
    CHECK(st.c_refused_rs_z == 0, "step %d: refused_rs_z %zu != 0", step, st.c_refused_rs_z);
    CHECK(st.c_refused_nrs == 0, "step %d: refused_nrs %zu != 0", step, st.c_refused_nrs);
    CHECK(st.c_patch_binds >= 1, "step %d: no in-place bind was applied", step);
    CHECK(st.c_applied == st.c_patch_binds,
          "step %d: applied %zu != patch_binds %zu", step, st.c_applied, st.c_patch_binds);

    // rs_z itself is a runtime index input, not a shape parameter; the
    // binder's recurrent lane covers n_rs and the head-selected views.
    CHECK(st.shape_map.rs_head_valid, "step %d: rs_head map invalid", step);
    CHECK(st.shape_map.nrs_valid, "step %d: n_rs map invalid", step);
}

static bool compare_logits(llama_context * a, llama_context * b, int n_vocab, int step,
                           const char * an, const char * bn) {
    ++g_checks_run;
    const float * la = llama_get_logits_ith(a, 0);
    const float * lb = llama_get_logits_ith(b, 0);
    if (la == nullptr || lb == nullptr) {
        std::fprintf(stderr, "FAIL step %d: missing logits %s=%p %s=%p\n",
                step, an, (const void *) la, bn, (const void *) lb);
        ++g_fail;
        return false;
    }
    if (std::memcmp(la, lb, (size_t) n_vocab * sizeof(float)) == 0) {
        return true;
    }
    float max_abs = 0.0f;
    int   max_i   = -1;
    for (int i = 0; i < n_vocab; ++i) {
        const float d = std::fabs(la[i] - lb[i]);
        if (d > max_abs) {
            max_abs = d;
            max_i   = i;
        }
    }
    std::fprintf(stderr,
            "FAIL step %d: logits %s vs %s differ (max_abs=%g at %d: %g vs %g)\n",
            step, an, bn, (double) max_abs, max_i,
            max_i >= 0 ? (double) la[max_i] : 0.0,
            max_i >= 0 ? (double) lb[max_i] : 0.0);
    ++g_fail;
    return false;
}

// Non-vacuity: the previous tiny GGUF (ca91c9fd...) read its leading tensors
// as zeros, so every logit was 0 and "ON == OFF" held for the wrong reason.
// A leg only counts when its logits are finite and actually vary across the
// vocabulary.
static bool check_logits_nonzero(const float * l, int n_vocab, int step,
                                 const char * leg, double * var_max) {
    ++g_checks_run;
    if (l == nullptr) {
        std::fprintf(stderr, "FAIL step %d (%s): missing logits\n", step, leg);
        ++g_fail;
        return false;
    }
    const float first   = l[0];
    double      sum     = 0.0;
    double      sumsq   = 0.0;
    int         distinct = 0;
    for (int i = 0; i < n_vocab; ++i) {
        if (!std::isfinite(l[i])) {
            std::fprintf(stderr, "FAIL step %d (%s): logit %d is not finite\n",
                    step, leg, i);
            ++g_fail;
            return false;
        }
        sum   += (double) l[i];
        sumsq += (double) l[i] * (double) l[i];
        if (l[i] != first) {
            ++distinct;
        }
    }
    const double mean = sum / (double) n_vocab;
    const double var  = sumsq / (double) n_vocab - mean * mean;
    if (var > *var_max) {
        *var_max = var;
    }
    if (!(var > 0.0) || distinct == 0) {
        std::fprintf(stderr,
                "FAIL step %d (%s): logits are constant (var=%g distinct=%d) - vacuous pass\n",
                step, leg, var, distinct);
        ++g_fail;
        return false;
    }
    return true;
}

static bool compare_states(llama_context * a, llama_context * b, int step,
                           const char * an, const char * bn) {
    ++g_checks_run;
    auto * ma = recr(a);
    auto * mb = recr(b);
    if (ma == nullptr || mb == nullptr) {
        std::fprintf(stderr, "FAIL step %d: missing recurrent memory (%s vs %s)\n",
                step, an, bn);
        ++g_fail;
        return false;
    }
    if (ma->r_l.size() != mb->r_l.size() || ma->s_l.size() != mb->s_l.size()) {
        std::fprintf(stderr, "FAIL step %d: layer count differs (%s vs %s)\n",
                step, an, bn);
        ++g_fail;
        return false;
    }
    for (size_t il = 0; il < ma->r_l.size(); ++il) {
        for (int which = 0; which < 2; ++which) {
            const ggml_tensor * ta = which == 0 ? ma->r_l[il] : ma->s_l[il];
            const ggml_tensor * tb = which == 0 ? mb->r_l[il] : mb->s_l[il];
            if (ta == nullptr || tb == nullptr) {
                std::fprintf(stderr, "FAIL step %d: layer %zu %s tensor is null (%s vs %s)\n",
                        step, il, which == 0 ? "r_l" : "s_l", an, bn);
                ++g_fail;
                return false;
            }
            const size_t na = ggml_nbytes(ta);
            const size_t nb = ggml_nbytes(tb);
            if (na != nb || std::memcmp(ta->data, tb->data, na) != 0) {
                std::fprintf(stderr,
                        "FAIL step %d: layer %zu %s state differs (%s vs %s, %zu vs %zu bytes)\n",
                        step, il, which == 0 ? "r_l" : "s_l", an, bn, na, nb);
                ++g_fail;
                return false;
            }
        }
    }
    return true;
}

// Same single-row contract as decode_one: only token 0 requests logits, so
// every decode here has exactly one output row. The scope is deliberate; a
// multi-row trace must extend compare_logits() and dump_step() first.
static bool decode_many(llama_context * ctx, const llama_token * toks,
                        const llama_pos * pos, const llama_seq_id * seqs, int n) {
    llama_batch b = llama_batch_init(n, 0, n);
    if (!llama_batch_is_complete(&b, n, false, true)) {
        llama_batch_free(b);
        return false;
    }
    b.n_tokens = n;
    for (int i = 0; i < n; ++i) {
        b.token[i]     = toks[i];
        b.pos[i]       = pos[i];
        b.n_seq_id[i]  = 1;
        b.seq_id[i][0] = seqs[i];
        b.logits[i]    = i == 0 ? 1 : 0;   // exactly one requested output row
    }

    const int rc = llama_decode(ctx, b);
    llama_batch_free(b);
    return rc == 0;
}

// one post-decode check block: the live memory, the binder's recorded bound
// values, the live tensor metadata, the counters, the graph order, and the
// stock-context oracle. The explicit-off leg must reproduce the stock leg
// exactly; the binder leg must reproduce both.
static void check_after_decode(llama_context * ctx_on, llama_context * ctx_off,
                               llama_context * ctx_stock,
                               llama_nkv_ctx_state & st, int step, int n_seqs,
                               int32_t rs_z, uint32_t head, uint32_t n_rs,
                               size_t expect_builds, bool expect_bind, int n_vocab,
                               size_t * prev_patch_binds) {
    auto * mem_on    = recr(ctx_on);
    auto * mem_off   = recr(ctx_off);
    auto * mem_stock = recr(ctx_stock);
    CHECK(mem_on != nullptr && mem_off != nullptr && mem_stock != nullptr,
          "step %d: missing recurrent memory (on=%p off=%p stock=%p)",
          step, (void *) mem_on, (void *) mem_off, (void *) mem_stock);
    if (mem_on == nullptr || mem_off == nullptr || mem_stock == nullptr) {
        return;
    }

    // the explicit-off leg must be the stock path, not just a quieter binder
    CHECK(mem_off->rs_z == mem_stock->rs_z && mem_off->head == mem_stock->head &&
          mem_off->n == mem_stock->n,
          "step %d: explicit OFF (rs_z/head/n_rs %d/%u/%u) != stock (%d/%u/%u)",
          step, mem_off->rs_z, mem_off->head, mem_off->n,
          mem_stock->rs_z, mem_stock->head, mem_stock->n);

    CHECK(mem_on->rs_z == rs_z,
          "step %d: live rs_z %d != expected %d", step, mem_on->rs_z, rs_z);
    CHECK(mem_on->head == head,
          "step %d: live head %u != expected %u", step, mem_on->head, head);
    CHECK(mem_on->n == n_rs,
          "step %d: live n_rs %u != expected %u", step, mem_on->n, n_rs);

    // record_bound_rs_z is diagnostic only: rs_z is a runtime index input,
    // and an rs_z-only move reuses the graph without calling the binder.
    if (expect_bind) {
        CHECK(st.record_bound_rs_z == mem_on->rs_z,
              "step %d: record_bound_rs_z %d != live %d",
              step, st.record_bound_rs_z, mem_on->rs_z);
    }
    CHECK(st.record_bound_rs_head == mem_on->head,
          "step %d: record_bound_rs_head %u != live %u",
          step, st.record_bound_rs_head, mem_on->head);
    CHECK(st.record_bound_n_rs == mem_on->n,
          "step %d: record_bound_n_rs %u != live %u",
          step, st.record_bound_n_rs, mem_on->n);
    CHECK(st.record_cap_nrs == mem_on->size,
          "step %d: record_cap_nrs %u != capacity %u",
          step, st.record_cap_nrs, mem_on->size);

    check_counters(st, step, expect_builds);
    check_live_tensors(ctx_on, st, step, n_seqs);
    check_zero_row(ctx_on, st, step);

    if (expect_bind) {
        CHECK(st.c_patch_binds > *prev_patch_binds,
              "step %d: no bind applied for a changed n_rs/head key (patch_binds %zu)",
              step, st.c_patch_binds);
    } else {
        CHECK(st.c_patch_binds == *prev_patch_binds,
              "step %d: an rs_z-only move called the binder (patch_binds %zu -> %zu)",
              step, *prev_patch_binds, st.c_patch_binds);
    }
    *prev_patch_binds = st.c_patch_binds;

    compare_logits(ctx_on,  ctx_off,   n_vocab, step, "on", "off");
    compare_logits(ctx_on,  ctx_stock, n_vocab, step, "on", "stock");
    compare_logits(ctx_off, ctx_stock, n_vocab, step, "off", "stock");
    compare_states(ctx_on,  ctx_stock, step, "on", "stock");
    compare_states(ctx_off, ctx_stock, step, "off", "stock");
}

int main(int argc, char ** argv) {
    if (argc != 2) {
        std::fprintf(stderr, "usage: %s <tiny-mamba.gguf>\n", argv[0]);
        return 2;
    }

    llama_backend_init();

    llama_model_params mp = llama_model_default_params();
    mp.n_gpu_layers = 0;

    llama_model * model = llama_model_load_from_file(argv[1], mp);
    if (model == nullptr) {
        std::fprintf(stderr, "FAIL: cannot load model %s\n", argv[1]);
        llama_backend_free();
        return 1;
    }

    const llama_vocab * vocab = llama_model_get_vocab(model);
    const int n_vocab = (int) llama_vocab_n_tokens(vocab);
    if (n_vocab < 262) {
        std::fprintf(stderr, "FAIL: tiny model has %d tokens, expected >= 262\n", n_vocab);
        llama_model_free(model);
        llama_backend_free();
        return 1;
    }

    // token ids of "a", "b", "c" in tests/rsz/make_tiny_rsz_mamba.py
    const llama_token tok_a = 259;
    const llama_token tok_b = 260;
    const llama_token tok_c = 261;

    // Three legs in one process: the gate is read in the llama_context
    // constructor and the binder state slot is per context, so the settings
    // cannot leak between legs.
    struct leg {
        const char *    name;
        const char *    gate;   // nullptr leaves GGML_TP5_UNION_BINDER unset
        llama_context * ctx;
        FILE *          dump;
        int             steps;
        int             nonzero;
        double          var_max;
        size_t          bytes;
    };
    leg legs[3] = {
        { "on",    "1",     nullptr, nullptr, 0, 0, 0.0, 0 },
        { "off",   "0",     nullptr, nullptr, 0, 0, 0.0, 0 },
        { "stock", nullptr, nullptr, nullptr, 0, 0, 0.0, 0 },
    };
    for (leg & L : legs) {
        L.ctx = make_ctx(model, L.gate);
    }
    if (legs[0].ctx == nullptr || legs[1].ctx == nullptr || legs[2].ctx == nullptr) {
        std::fprintf(stderr, "FAIL: context creation failed (on=%p off=%p stock=%p)\n",
                (void *) legs[0].ctx, (void *) legs[1].ctx, (void *) legs[2].ctx);
        for (leg & L : legs) {
            if (L.ctx != nullptr) {
                llama_free(L.ctx);
            }
        }
        llama_model_free(model);
        llama_backend_free();
        return 1;
    }
    llama_context * ctx_on    = legs[0].ctx;
    llama_context * ctx_off   = legs[1].ctx;
    llama_context * ctx_stock = legs[2].ctx;

    // Raw logits dump: one float32 stream per leg, every step in order. The
    // external sha256sum of the three files is the RESULT table; the
    // in-process memcmp in check_after_decode is the actual bitwise gate.
    const char * dump_dir = std::getenv("RSZ_LOGITS_DIR");
    if (dump_dir != nullptr) {
        for (leg & L : legs) {
            char path[1024];
            std::snprintf(path, sizeof(path), "%s/logits-%s.bin", dump_dir, L.name);
            L.dump = std::fopen(path, "wb");
            CHECK(L.dump != nullptr, "cannot open logits dump %s", path);
        }
    } else {
        std::printf("RSZ_LOGITS_DUMP skipped: RSZ_LOGITS_DIR is unset\n");
    }

    auto dump_step = [&](leg & L, int step_i) {
        const float * l = llama_get_logits_ith(L.ctx, 0);
        ++L.steps;
        if (check_logits_nonzero(l, n_vocab, step_i, L.name, &L.var_max)) {
            ++L.nonzero;
        }
        if (l == nullptr) {
            return;
        }
        if (L.dump != nullptr) {
            const size_t bytes = (size_t) n_vocab * sizeof(float);
            const size_t nw = std::fwrite(l, 1, bytes, L.dump);
            CHECK(nw == bytes, "leg %s: short logits dump (%zu of %zu bytes)",
                  L.name, nw, bytes);
            L.bytes += nw;
        }
    };

    auto & st = llama_nkv_ctx_state_get(ctx_on);
    CHECK(st.nkv_enabled, "binder context did not enable the union binder");
    CHECK(st.union_binder.has(llama_union_param_kind::rs_z), "rs_z binding is not registered");

    auto * mem_on    = recr(ctx_on);
    auto * mem_stock = recr(ctx_stock);
    CHECK(mem_on    != nullptr, "binder context memory is not recurrent");
    CHECK(mem_stock != nullptr, "stock context memory is not recurrent");

    struct step {
        const char * name;
        llama_token  tok;
        llama_pos    pos;
        int32_t      rs_z;
        uint32_t     head;
    };

    // Phase A: one sequence, single-token ubatches. The first decode builds
    // the envelope graph; the following moves exercise rs_z 0 -> -1 -> 1 ->
    // -1 -> 0 and head 0 -> 1 -> 0 without a rebuild.
    const std::vector<step> steps = {
        { "first build",            tok_a, 0,  0, 0 },
        { "rs_z 0->-1",             tok_b, 1, -1, 0 },
        { "seq_cp + head/rs_z 1",   tok_c, 2,  1, 1 },
        { "rs_z 1->-1",             tok_a, 3, -1, 1 },
        { "seq_rm all + rs_z 0",    tok_b, 4,  0, 0 },
        { "rs_z 0->-1 again",       tok_c, 5, -1, 0 },
    };

    size_t prev_patch_binds = 0;

    std::vector<int32_t>  rs_z_seen;
    std::vector<uint32_t> head_seen;
    std::vector<uint32_t> nrs_seen;
    auto note_live = [&]() {
        rs_z_seen.push_back(mem_on->rs_z);
        head_seen.push_back(mem_on->head);
        nrs_seen.push_back(mem_on->n);
    };

    uint32_t last_head = mem_on->head;
    uint32_t last_nrs  = mem_on->n;

    for (size_t i = 0; i < steps.size(); ++i) {
        const step & s = steps[i];
        const int step_i = (int) i;

        if (i == 2) {
            // share seq 0's cell with seq 1 so the next seq-0 decode must move
            // to a fresh cell: head becomes 1 and the zero row is the new head.
            llama_memory_seq_cp(llama_get_memory(ctx_on),    0, 1, -1, -1);
            llama_memory_seq_cp(llama_get_memory(ctx_off),   0, 1, -1, -1);
            llama_memory_seq_cp(llama_get_memory(ctx_stock), 0, 1, -1, -1);
        }
        if (i == 4) {
            // release every sequence: the next decode allocates cell 0 again.
            llama_memory_seq_rm(llama_get_memory(ctx_on),    -1, -1, -1);
            llama_memory_seq_rm(llama_get_memory(ctx_off),   -1, -1, -1);
            llama_memory_seq_rm(llama_get_memory(ctx_stock), -1, -1, -1);
        }

        CHECK(decode_one(ctx_on,    s.tok, s.pos, 0), "step %zu (%s): ON decode failed", i, s.name);
        CHECK(decode_one(ctx_off,   s.tok, s.pos, 0), "step %zu (%s): OFF decode failed", i, s.name);
        CHECK(decode_one(ctx_stock, s.tok, s.pos, 0), "step %zu (%s): stock decode failed", i, s.name);

        const bool expect_bind = i == 0 || mem_on->head != last_head || mem_on->n != last_nrs;
        check_after_decode(ctx_on, ctx_off, ctx_stock, st, step_i, 1,
                           mem_stock->rs_z, mem_stock->head, mem_stock->n,
                           1, expect_bind, n_vocab, &prev_patch_binds);
        for (leg & L : legs) {
            dump_step(L, step_i);
        }
        CHECK(st.c_graph_builds == 1, "step %zu (%s): graph_builds %zu != 1",
              i, s.name, st.c_graph_builds);

        note_live();
        last_head = mem_on->head;
        last_nrs  = mem_on->n;
    }

    CHECK(st.c_graph_builds == 1, "phase A: graph_builds %zu != 1", st.c_graph_builds);

    // Phase B: n_rs change across the same 2-sequence skeleton.
    // Clear the phase-A state, create four filler sequences in cells 0..3
    // (a legitimate 4-sequence skeleton rebuild), then two 2-sequence
    // ubatches: B1 puts seq 0/1 in cells 4/5 (n_rs=2); a memory-only move
    // puts seq 1 in cell 1, so B2 has n_rs=4 without a skeleton change. The
    // envelope sized copy at the full 8-cell capacity, so B2 binds in place.
    llama_memory_seq_rm(llama_get_memory(ctx_on),    -1, -1, -1);
    llama_memory_seq_rm(llama_get_memory(ctx_off),   -1, -1, -1);
    llama_memory_seq_rm(llama_get_memory(ctx_stock), -1, -1, -1);

    const llama_token fill_toks[4] = { tok_a, tok_a, tok_a, tok_a };
    const llama_pos   fill_pos[4]  = { 0, 0, 0, 0 };
    const llama_seq_id fill_seqs[4] = { 4, 5, 6, 7 };
    CHECK(decode_many(ctx_on,    fill_toks, fill_pos, fill_seqs, 4), "phase B filler: ON decode failed");
    CHECK(decode_many(ctx_off,   fill_toks, fill_pos, fill_seqs, 4), "phase B filler: OFF decode failed");
    CHECK(decode_many(ctx_stock, fill_toks, fill_pos, fill_seqs, 4), "phase B filler: stock decode failed");
    check_after_decode(ctx_on, ctx_off, ctx_stock, st, 6, 4,
                       mem_stock->rs_z, mem_stock->head, mem_stock->n,
                       2, true, n_vocab, &prev_patch_binds);
    for (leg & L : legs) {
        dump_step(L, 6);
    }
    CHECK(st.c_graph_builds == 2, "phase B filler: graph_builds %zu != 2", st.c_graph_builds);
    note_live();

    const llama_token b1_toks[2] = { tok_a, tok_b };
    const llama_pos   b1_pos[2]  = { 0, 0 };
    const llama_seq_id b1_seqs[2] = { 0, 1 };
    CHECK(decode_many(ctx_on,    b1_toks, b1_pos, b1_seqs, 2), "phase B1: ON decode failed");
    CHECK(decode_many(ctx_off,   b1_toks, b1_pos, b1_seqs, 2), "phase B1: OFF decode failed");
    CHECK(decode_many(ctx_stock, b1_toks, b1_pos, b1_seqs, 2), "phase B1: stock decode failed");
    check_after_decode(ctx_on, ctx_off, ctx_stock, st, 7, 2,
                       mem_stock->rs_z, mem_stock->head, mem_stock->n,
                       3, true, n_vocab, &prev_patch_binds);
    for (leg & L : legs) {
        dump_step(L, 7);
    }
    CHECK(st.c_graph_builds == 3, "phase B1: graph_builds %zu != 3", st.c_graph_builds);
    CHECK(mem_on->n == 2, "phase B1: n_rs %u != 2", mem_on->n);
    note_live();

    // Move seq 1 from cell 5 to cell 1 (owned by filler seq 5), then release
    // the filler: seq 1 now owns cell 1. No graph is built by these calls.
    llama_memory_seq_rm(llama_get_memory(ctx_on),    1, -1, -1);
    llama_memory_seq_rm(llama_get_memory(ctx_off),   1, -1, -1);
    llama_memory_seq_rm(llama_get_memory(ctx_stock), 1, -1, -1);
    llama_memory_seq_cp(llama_get_memory(ctx_on),    5, 1, -1, -1);
    llama_memory_seq_cp(llama_get_memory(ctx_off),   5, 1, -1, -1);
    llama_memory_seq_cp(llama_get_memory(ctx_stock), 5, 1, -1, -1);
    llama_memory_seq_rm(llama_get_memory(ctx_on),    5, -1, -1);
    llama_memory_seq_rm(llama_get_memory(ctx_off),   5, -1, -1);
    llama_memory_seq_rm(llama_get_memory(ctx_stock), 5, -1, -1);

    const llama_token b2_toks[2] = { tok_c, tok_a };
    const llama_pos   b2_pos[2]  = { 1, 1 };
    const llama_seq_id b2_seqs[2] = { 0, 1 };
    CHECK(decode_many(ctx_on,    b2_toks, b2_pos, b2_seqs, 2), "phase B2: ON decode failed");
    CHECK(decode_many(ctx_off,   b2_toks, b2_pos, b2_seqs, 2), "phase B2: OFF decode failed");
    CHECK(decode_many(ctx_stock, b2_toks, b2_pos, b2_seqs, 2), "phase B2: stock decode failed");

    CHECK(mem_on->n == 4, "phase B2: n_rs %u != 4 (expected the 2->4 change)", mem_on->n);
    CHECK(st.c_graph_builds == 3,
          "phase B2: graph_builds %zu != 3 (n_rs change rebuilt the graph)", st.c_graph_builds);
    check_after_decode(ctx_on, ctx_off, ctx_stock, st, 8, 2,
                       mem_stock->rs_z, mem_stock->head, mem_stock->n,
                       3, true, n_vocab, &prev_patch_binds);
    for (leg & L : legs) {
        dump_step(L, 8);
    }
    CHECK(st.c_graph_builds == 3,
          "phase B2: graph_builds %zu != 3 after the n_rs bind", st.c_graph_builds);
    note_live();

    // Coverage: the run must have moved rs_z (including the -1 no-op), the
    // head, and n_rs, all without a rebuild after the three skeleton builds.
    CHECK(std::find(rs_z_seen.begin(), rs_z_seen.end(), 0) != rs_z_seen.end(),
          "rs_z never took the present row 0");
    CHECK(std::find(rs_z_seen.begin(), rs_z_seen.end(), -1) != rs_z_seen.end(),
          "rs_z never took the -1 no-op value");
    CHECK(std::find(head_seen.begin(), head_seen.end(), 1) != head_seen.end(),
          "head never moved to row 1");
    CHECK(std::find(nrs_seen.begin(), nrs_seen.end(), 2) != nrs_seen.end(),
          "n_rs never took the 2-cell width");
    CHECK(std::find(nrs_seen.begin(), nrs_seen.end(), 4) != nrs_seen.end(),
          "n_rs never took the 4-cell width");
    CHECK(st.c_graph_builds == 3, "final graph_builds %zu != 3", st.c_graph_builds);

    // Close the dumps before printing so the RESULT table can hash them.
    for (leg & L : legs) {
        if (L.dump != nullptr) {
            CHECK(std::ferror(L.dump) == 0, "leg %s: logits dump stream error", L.name);
            CHECK(std::fclose(L.dump) == 0, "leg %s: fclose failed", L.name);
            L.dump = nullptr;
        }
    }

    std::printf("RSZ_STATS graph_builds=%zu env_builds=%zu patch_binds=%zu applied=%zu "
                "refused_rs_z=%zu refused_nrs=%zu shape_fail=%zu env_disabled=%d "
                "cap_nrs=%u bound_rs_z=%d bound_head=%u\n",
            st.c_graph_builds, st.c_env_builds, st.c_patch_binds, st.c_applied,
            st.c_refused_rs_z, st.c_refused_nrs, st.c_shape_fail, st.env_disabled ? 1 : 0,
            st.record_cap_nrs, st.record_bound_rs_z, st.record_bound_rs_head);

    for (const leg & L : legs) {
        std::printf("RSZ_LOGITS leg=%s steps=%d nonzero=%d var_max=%.6g bytes=%zu\n",
                L.name, L.steps, L.nonzero, L.var_max, L.bytes);
        CHECK(L.steps > 0 && L.nonzero == L.steps,
              "leg %s: %d of %d steps had vacuous (constant or non-finite) logits",
              L.name, L.steps - L.nonzero, L.steps);
    }
    if (dump_dir != nullptr) {
        CHECK(legs[0].bytes == legs[1].bytes && legs[0].bytes == legs[2].bytes,
              "logits dump sizes differ (%zu / %zu / %zu)",
              legs[0].bytes, legs[1].bytes, legs[2].bytes);
    }

    for (leg & L : legs) {
        llama_free(L.ctx);
    }
    llama_model_free(model);
    llama_backend_free();

    if (g_checks_run == 0) {
        std::fprintf(stderr, "RSZ_BINDER_TEST UNPROVEN reason=no_check_ran checks=0\n");
        return 2;
    }
    if (g_fail != 0) {
        std::printf("RSZ_BINDER_TEST FAIL %d check(s)\n", g_fail);
        return 1;
    }
    std::printf("RSZ_BINDER_TEST PASS\n");
    return 0;
}
